#!/usr/bin/env bash
# Tanveer Discord Bot installer for Ubuntu and Debian (systemd).
#   git clone https://github.com/Tanveer9830/650-discord-bot-V2.git && cd 650-discord-bot-V2 && sudo bash install.sh
# Options: --reconfigure (re-enter credentials), --no-start (install without starting the service).
# The installer never asks for GitHub credentials and never pipes a remote script into a shell.
set -Eeuo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=deploy/lib.sh
. "${SRC_DIR}/deploy/lib.sh"

RECONFIGURE=0
NO_START=0
for arg in "$@"; do
  case "$arg" in
    --reconfigure) RECONFIGURE=1 ;;
    --no-start) NO_START=1 ;;
    -h|--help) sed -n '2,6p' "$0"; exit 0 ;;
    *) die "Unknown option: $arg" ;;
  esac
done

trap 'die "Installation stopped at line $LINENO. Nothing secret was printed. Fix the problem above and run the installer again."' ERR

require_root
check_os
for cmd in curl tar xz sha256sum sed install useradd runuser; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    info "Installing missing prerequisites"
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y -qq
    apt-get install -y -qq --no-install-recommends ca-certificates curl xz-utils tar coreutils sed util-linux passwd
    break
  fi
done

print_banner
echo
info "Installing Node.js"
install_node

info "Preparing the service account and directories"
ensure_system_user
ensure_dirs

info "Copying the application to $APP_DIR"
sync_app "$SRC_DIR"

prompt_secret_token() {
  local value
  while true; do
    read -r -s -p "Discord bot token (input hidden): " value </dev/tty; echo
    if [[ "$value" =~ ^[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{4,}\.[A-Za-z0-9_-]{20,}$ ]]; then
      printf '%s' "$value"; return 0
    fi
    echo "That does not look like a Discord bot token. Try again (Ctrl+C to stop)." >&2
  done
}

write_env_file() {
  local token="$1" client_id="$2" owners="$3" dev_guild="$4"
  local tmp
  umask 077
  tmp="$(mktemp)"
  {
    echo "# Generated by install.sh. Do not commit. Edit with: sudo nano ${ENV_FILE}"
    printf 'DISCORD_TOKEN=%s\n' "$token"
    printf 'DISCORD_CLIENT_ID=%s\n' "$client_id"
    [ -n "$dev_guild" ] && printf 'DISCORD_DEV_GUILD_ID=%s\n' "$dev_guild"
    printf 'OWNER_IDS=%s\n' "$owners"
    echo "NODE_ENV=production"
    echo "LOG_LEVEL=info"
    echo "LOG_FORMAT=json"
  } > "$tmp"
  install -m 0640 -o root -g "$SERVICE_USER" "$tmp" "$ENV_FILE"
  rm -f "$tmp"
  umask 022
}

if [ -f "$ENV_FILE" ] && [ "$RECONFIGURE" -eq 0 ]; then
  ok "Keeping the existing configuration at $ENV_FILE (use --reconfigure to change it)"
else
  info "Configuration"
  if [ "${TANVEER_NONINTERACTIVE:-0}" = "1" ]; then
    : "${DISCORD_TOKEN:?Set DISCORD_TOKEN in the environment for a non-interactive install}"
    : "${DISCORD_CLIENT_ID:?Set DISCORD_CLIENT_ID in the environment for a non-interactive install}"
    token="$DISCORD_TOKEN"; client_id="$DISCORD_CLIENT_ID"
    owners="${OWNER_IDS:-1131248987173814336}"; dev_guild="${DISCORD_DEV_GUILD_ID:-}"
  else
    [ -r /dev/tty ] || die "No terminal available for prompts. Re-run in an interactive shell, or set TANVEER_NONINTERACTIVE=1 with DISCORD_TOKEN and DISCORD_CLIENT_ID."
    token="$(prompt_secret_token)"
    while true; do
      read -r -p "Discord application (client) ID: " client_id </dev/tty
      [[ "$client_id" =~ ^[0-9]{17,20}$ ]] && break
      echo "The client ID is a 17 to 20 digit number. Try again." >&2
    done
    read -r -p "Global owner user IDs, comma-separated [1131248987173814336]: " owners </dev/tty
    owners="${owners:-1131248987173814336}"
    [[ "$owners" =~ ^[0-9]{17,20}(,[0-9]{17,20})*$ ]] || die "Owner IDs must be numeric Discord user IDs separated by commas."
    read -r -p "Test server ID for instant command registration (optional, press Enter to skip): " dev_guild </dev/tty
    if [ -n "$dev_guild" ] && ! [[ "$dev_guild" =~ ^[0-9]{17,20}$ ]]; then die "The test server ID must be a numeric ID."; fi
  fi
  write_env_file "$token" "$client_id" "$owners" "${dev_guild:-}"
  unset token
  ok "Wrote $ENV_FILE (owner root, group $SERVICE_USER, mode 0640)"
fi

info "Preparing the database"
run_as_service scripts/migrate.js

info "Checking configuration and command definitions (no Discord login)"
run_as_service src/index.js --check >/dev/null
ok "Configuration, migrations and command definitions are valid"

if have_systemd; then
  info "Installing the systemd service"
  render_unit
  systemctl enable "$APP_NAME" >/dev/null
  if [ "$NO_START" -eq 0 ]; then
    systemctl restart "$APP_NAME"
    sleep 5
    if systemctl is-active --quiet "$APP_NAME"; then
      ok "Service is running. Follow its log with: sudo journalctl -u $APP_NAME -f"
    else
      warn "Service is not running yet. Check: sudo journalctl -u $APP_NAME -n 50 --no-pager"
      warn "A wrong token shows up here as a login failure. Fix it with: sudo bash install.sh --reconfigure"
    fi
  else
    ok "Service installed and enabled but not started (--no-start)"
  fi
else
  warn "systemd was not detected. The service unit was not installed."
  warn "Start the bot manually with: cd $APP_DIR && sudo -u $SERVICE_USER env ENV_FILE=$ENV_FILE $NODE_BIN src/index.js"
fi

read -r -p "Register slash commands globally now? Takes up to an hour to appear everywhere. [y/N]: " reg </dev/tty || reg="n"
if [[ "${reg,,}" == "y" || "${reg,,}" == "yes" ]]; then
  run_as_service scripts/register-commands.js --scope global
else
  echo "Skipped. Register later with: sudo runuser -u $SERVICE_USER -- env ENV_FILE=$ENV_FILE $NODE_BIN $APP_DIR/scripts/register-commands.js --scope global"
fi

echo
print_banner
echo
ok "Installation finished. Made by Tanveer | Discord: tanveer5637"
echo "Useful commands:"
echo "  sudo systemctl status $APP_NAME"
echo "  sudo journalctl -u $APP_NAME -f"
echo "  sudo bash update.sh      (run from your clone directory)"
echo "  sudo bash uninstall.sh   (run from your clone directory)"
